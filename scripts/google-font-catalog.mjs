const categories = new Set(["serif", "sans-serif", "display", "handwriting", "monospace"]);

export function resolveCatalogLimit(value) {
  const requested = Number(value ?? 300);
  return Number.isInteger(requested) ? Math.min(1000, Math.max(30, requested)) : 300;
}

export function normalizeGoogleFont(value) {
  if (!value || typeof value !== "object") return null;
  if (typeof value.family !== "string" || !/^[a-zA-Z0-9 _-]{1,100}$/.test(value.family)) {
    return null;
  }
  if (!categories.has(value.category) || !Array.isArray(value.variants)) return null;

  const normalWeights = new Set();
  const italicWeights = new Set();
  for (const variant of value.variants) {
    if (variant === "regular") {
      normalWeights.add(400);
      continue;
    }
    if (variant === "italic") {
      italicWeights.add(400);
      continue;
    }
    const match = /^(\d{3})(italic)?$/.exec(String(variant));
    if (!match) continue;
    const weight = Number(match[1]);
    if (weight < 100 || weight > 900) continue;
    (match[2] ? italicWeights : normalWeights).add(weight);
  }
  if (normalWeights.size === 0 && italicWeights.size === 0) normalWeights.add(400);

  const weights = new Set([...normalWeights, ...italicWeights]);
  const styles = [
    ...(normalWeights.size > 0 ? ["normal"] : []),
    ...(italicWeights.size > 0 ? ["italic"] : []),
  ].sort();

  const subsets = Array.isArray(value.subsets)
    ? value.subsets.filter(
        (subset) => typeof subset === "string" && /^[a-z0-9-]{1,40}$/.test(subset),
      )
    : [];
  const weightAxis = Array.isArray(value.axes)
    ? value.axes.find(
        (axis) =>
          axis &&
          typeof axis === "object" &&
          axis.tag === "wght" &&
          Number.isFinite(axis.start) &&
          Number.isFinite(axis.end) &&
          axis.start >= 1 &&
          axis.end <= 1000 &&
          axis.start < axis.end,
      )
    : undefined;

  return {
    family: value.family,
    category: value.category,
    weights: [...weights].sort((a, b) => a - b),
    styles,
    styleWeights: {
      normal: [...normalWeights].sort((a, b) => a - b),
      italic: [...italicWeights].sort((a, b) => a - b),
    },
    subsets: [...new Set(subsets)].sort(),
    ...(typeof value.lastModified === "string" && /^\d{4}-\d{2}-\d{2}$/.test(value.lastModified)
      ? { lastModified: value.lastModified }
      : {}),
    ...(weightAxis ? { variableWeight: { min: weightAxis.start, max: weightAxis.end } } : {}),
  };
}

export function renderGoogleFontsCatalog(fonts, generatedAt = new Date().toISOString()) {
  return `// Generated by scripts/sync-google-fonts.mjs. Do not edit manually.\nexport const GOOGLE_FONTS_CATALOG_META = ${JSON.stringify(
    {
      source: "google-fonts-developer-api",
      generatedAt,
      limit: fonts.length,
    },
    null,
    2,
  )} as const;\n\nexport const GOOGLE_FONTS_CATALOG = ${JSON.stringify(fonts, null, 2)} as const;\n`;
}
